"""viz-dither — hard-edged 1-bit pixel icon set (self-authored, secure).

12x12 bitmaps in the same 1-bit family as the dither imagery, so icons and
graphics read as one system. Single source of truth here; emits:
  1. a contact-sheet PNG for isolated legibility review, and
  2. <out>/pixel-icons.js  ([x,y] filled-cell data for a <PixelIcon> component).

Icons render with currentColor, so they tint to any palette value in CSS.
Add your own glyphs by appending '#'/'.' grids to ICONS.

Usage: python3 pixel_icons.py --out ./icons
"""
